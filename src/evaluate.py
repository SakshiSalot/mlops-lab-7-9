"""Stage 5: evaluate a fitted pipeline on held-out data and write reproducible reports.

    evaluate_model(model, X_test, y_test)  -> metrics dict
    write_reports(...)                       -> reports/metrics.json, reports/evaluation.md, figure

Run on its own to re-score the saved model on the saved test split; the numbers
must match the ones recorded at training time (reproducibility check):
    python -m src.evaluate
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.metrics import mean_absolute_error, mean_absolute_percentage_error, mean_squared_error, r2_score

from src import schema
from src.config import load_config, resolve


def evaluate_model(model, X_test: pd.DataFrame, y_test: pd.Series) -> dict:
    pred = model.predict(X_test)
    baseline = np.full(len(y_test), float(np.mean(y_test)))
    return {
        "test_mae": float(mean_absolute_error(y_test, pred)),
        "test_rmse": float(np.sqrt(mean_squared_error(y_test, pred))),
        "test_r2": float(r2_score(y_test, pred)),
        "test_mape": float(mean_absolute_percentage_error(y_test, pred)),
        "baseline_rmse_predict_mean": float(np.sqrt(mean_squared_error(y_test, baseline))),
        "test_rows": int(len(y_test)),
    }


def residual_figure(model, X_test, y_test, path: Path) -> Path | None:
    """Predicted-vs-actual and residual plots. matplotlib is a dev dependency, so this is optional."""
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        return None
    ink, ink2, grid, surface, series = "#0b0b0b", "#52514e", "#e4e3df", "#fcfcfb", "#2a78d6"
    y = np.asarray(y_test)
    p = model.predict(X_test)
    fig, (a1, a2) = plt.subplots(1, 2, figsize=(10, 4), facecolor=surface)
    lo, hi = min(y.min(), p.min()), max(y.max(), p.max())
    a1.plot([lo, hi], [lo, hi], color=ink2, lw=1, ls="--", label="perfect prediction")
    a1.scatter(y, p, s=14, color=series, alpha=0.7, edgecolors=surface, linewidths=0.5)
    a2.axhline(0, color=ink2, lw=1, ls="--")
    a2.scatter(p, y - p, s=14, color=series, alpha=0.7, edgecolors=surface, linewidths=0.5)
    for ax, title, xl, yl in [(a1, "Predicted vs actual (test split)", "Actual price (lakhs)", "Predicted price (lakhs)"),
                              (a2, "Residuals (actual - predicted)", "Predicted price (lakhs)", "Residual (lakhs)")]:
        ax.set_facecolor(surface)
        ax.set_title(title, color=ink, fontsize=11, loc="left")
        ax.set_xlabel(xl, color=ink2, fontsize=9)
        ax.set_ylabel(yl, color=ink2, fontsize=9)
        ax.tick_params(colors=ink2, labelsize=8)
        ax.grid(color=grid, lw=0.8)
        ax.set_axisbelow(True)
        for s in ("top", "right"):
            ax.spines[s].set_visible(False)
        for s in ("left", "bottom"):
            ax.spines[s].set_color(grid)
    a1.legend(frameon=False, fontsize=8, labelcolor=ink2)
    fig.tight_layout()
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=130, facecolor=surface, metadata={"Software": None})
    plt.close(fig)
    return path


def write_reports(metrics: dict, cv: dict, metadata: dict, data_report: dict, reports_dir: str | Path,
                  model=None, X_test=None, y_test=None) -> None:
    rdir = resolve(reports_dir)
    rdir.mkdir(parents=True, exist_ok=True)
    payload = {**{k: round(v, 6) if isinstance(v, float) else v for k, v in metrics.items()},
               **{k: round(v, 6) for k, v in cv.items()}}
    (rdir / "metrics.json").write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    fig = residual_figure(model, X_test, y_test, rdir / "figures" / "residuals.png") if model is not None else None

    improvement = 1 - metrics["test_rmse"] / metrics["baseline_rmse_predict_mean"]
    lines = [
        "# Evaluation report",
        "",
        "Generated by `python -m src.train` (re-check with `python -m src.evaluate`). "
        "Deterministic: same data + config + code -> same numbers.",
        "",
        "| Item | Value |",
        "|---|---|",
        f"| Model | `{metadata['model_type']}` {json.dumps(metadata['params'])} |",
        f"| Model file / SHA-256 | `models/model.joblib` / `{metadata['model_sha256'][:16]}...` |",
        f"| Raw data md5 | `{data_report['raw_md5']}` ({data_report['raw_rows']} raw rows) |",
        f"| Rows after cleaning | {data_report['clean_rows']} (train {data_report['train_rows']}, test {data_report['test_rows']}) |",
        f"| Split | random, test_size={metadata['split']['test_size']}, random_state={metadata['split']['random_state']} |",
        "",
        "## Held-out test metrics (price in INR lakhs)",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| MAE | {metrics['test_mae']:.3f} |",
        f"| RMSE | {metrics['test_rmse']:.3f} |",
        f"| R2 | {metrics['test_r2']:.4f} |",
        f"| MAPE | {metrics['test_mape']:.2%} |",
        f"| Baseline RMSE (always predict the mean) | {metrics['baseline_rmse_predict_mean']:.3f} |",
        f"| RMSE reduction vs baseline | {improvement:.1%} |",
        "",
        "## Stability (cross-validation on the training split only)",
        "",
        f"{cv['cv_folds']}-fold CV RMSE: {cv['cv_rmse_mean']:.3f} +/- {cv['cv_rmse_std']:.3f}. "
        "The test split is never used for fitting or model selection.",
    ]
    if fig:
        lines += ["", "![Residuals](figures/residuals.png)"]
    (rdir / "evaluation.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    from src.predict import load_model

    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--config", default=None)
    ap.add_argument("--model-path", default=None)
    args = ap.parse_args()
    cfg = load_config(args.config)
    loaded = load_model(args.model_path or resolve(cfg["artifacts"]["model_path"]))
    test = pd.read_csv(resolve(cfg["data"]["processed_dir"]) / "test.csv")
    metrics = evaluate_model(loaded.pipeline, test[schema.INPUT_FEATURES], test[schema.TARGET])
    recorded = loaded.metadata["metrics"]
    same = all(abs(metrics[k] - recorded[k]) < 1e-9 for k in ("test_mae", "test_rmse", "test_r2"))
    print(json.dumps(metrics, indent=2))
    print("matches metrics recorded at training time:", same)
    if not same:
        raise SystemExit("re-evaluation does not match the training-time metrics")


if __name__ == "__main__":
    main()
